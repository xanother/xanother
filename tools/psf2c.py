# psf to c header converter for the terminal font. reads psf1 and psf2
# console fonts (optionally gzip compressed), follows the embedded
# unicode table and emits a self contained header: glyph bitmaps plus a
# sorted codepoint to glyph index map for binary search at runtime.
# provenance lives in the generated header comment, the source file
# itself is not committed

import argparse
import gzip
import struct
import sys
from pathlib import Path

PSF1_MAGIC = 0x0436
PSF1_MODEHAS512 = 0x01
PSF1_MODEHASTAB = 0x02
PSF2_MAGIC = 0x864AB572
SEP = 0xFFFE
START = 0xFFFF
FALLBACK = ord("?")


def read_table_psf1(data, offset, n_glyphs):
    pairs = []
    glyph = 0
    pos = offset
    while glyph < n_glyphs and pos + 2 <= len(data):
        (w,) = struct.unpack_from("<H", data, pos)
        pos += 2
        if w == START:
            glyph += 1
        elif w == SEP:
            continue
        else:
            pairs.append((w, glyph))
    return pairs


def read_table_psf2(data, offset, n_glyphs):
    pairs = []
    glyph = 0
    pos = offset
    while glyph < n_glyphs and pos + 2 <= len(data):
        (w,) = struct.unpack_from("<H", data, pos)
        pos += 2
        if w == START:
            glyph += 1
        elif w == SEP:
            continue
        else:
            pairs.append((w, glyph))
    return pairs


def convert(path):
    raw = Path(path).read_bytes()
    if path.endswith(".gz"):
        raw = gzip.decompress(raw)

    pairs = []
    if len(raw) >= 6 and struct.unpack_from("<H", raw, 0)[0] == PSF1_MAGIC:
        mode = raw[2]
        charsize = raw[3]
        n = 512 if mode & PSF1_MODEHAS512 else 256
        width, height = 8, charsize
        glyph_bytes = raw[4:4 + n * charsize]
        if mode & PSF1_MODEHASTAB:
            pairs = read_table_psf1(raw, 4 + n * charsize, n)
    elif len(raw) >= 32 and struct.unpack_from("<I", raw, 0)[0] == PSF2_MAGIC:
        (_, _, hsize, _, n, charsize, height, width) = \
            struct.unpack_from("<8I", raw, 0)
        glyph_bytes = raw[hsize:hsize + n * charsize]
        pairs = read_table_psf2(raw, hsize + n * charsize, n)
    else:
        raise SystemExit(f"{path}: neither psf1 nor psf2")

    # first occurrence wins, duplicates collapse; the map is sorted for
    # binary search, the fallback glyph keeps unfonted codepoints sane
    seen = {}
    for cp, g in pairs:
        if cp not in seen:
            seen[cp] = g
    seen[FALLBACK] = seen.get(FALLBACK, FALLBACK)
    mapping = sorted(seen.items())
    return width, height, n, glyph_bytes, mapping


def emit(width, height, n, glyph_bytes, mapping, source, out):
    lines = []
    lines.append("// generated by tools/psf2c.py from " + source)
    lines.append("// font: terminus, (c) dimitar toshikov zhekov, free")
    lines.append("// font license, distributed with debian console-setup;")
    lines.append("// do not edit, regenerate with the tool instead")
    lines.append("//")
    lines.append("// SPDX-License-Identifier: MIT")
    lines.append("")
    lines.append("#ifndef X12_TERM_FONT_H")
    lines.append("#define X12_TERM_FONT_H")
    lines.append("")
    lines.append(f"#define FONT_W {width}")
    lines.append(f"#define FONT_H {height}")
    lines.append(f"#define FONT_GLYPHS {n}")
    lines.append("")
    lines.append(f"static const uint8_t x12term_glyphs[{n} * {height}] = {{")
    row_bytes = (width + 7) // 8
    for g in range(n):
        chunk = glyph_bytes[g * height:(g + 1) * height]
        cells = []
        for b in chunk:
            cells.append(f"0x{b:02x}")
        lines.append("    " + ", ".join(cells) + f",  // glyph {g}")
    lines.append("};")
    lines.append("")
    lines.append("// codepoint to glyph index, sorted by codepoint for")
    lines.append("// binary search; missing codepoints render as the")
    lines.append("// fallback glyph instead")
    lines.append("static const struct x12term_map_entry {")
    lines.append("    uint32_t cp;")
    lines.append("    uint16_t glyph;")
    lines.append(f"}} x12term_map[] = {{")
    for cp, g in mapping:
        lines.append(f"    {{ 0x{cp:04x}, {g} }},")
    lines.append("};")
    lines.append("")
    lines.append(f"#define X12TERM_MAP_LEN {len(mapping)}")
    lines.append("")
    lines.append("#endif")
    out.write_text("\n".join(lines) + "\n")
    print(f"{out}: {n} glyphs {width}x{height}, {len(mapping)} map entries")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("font")
    ap.add_argument("out")
    a = ap.parse_args()
    width, height, n, glyph_bytes, mapping = convert(a.font)
    emit(width, height, n, glyph_bytes, mapping, a.font, Path(a.out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
